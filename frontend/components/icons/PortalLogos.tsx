/**
 * Convenience component that displays the corresponding brand icon for a given source key.
 */
export function PortalIcon({
  source,
  className = "h-3.5 w-3.5",
}: {
  source?: string | null;
  className?: string;
}) {
  const norm = (source || "ikman").toLowerCase().trim();
  if (norm.includes("lpw") || norm.includes("lankapropertyweb") || norm.includes("lkpw")) {
    return <LpwIcon className={className} />;
  }
  if (norm.includes("ikman")) {
    return <IkmanIcon className={className} />;
  }
  return <Globe className={className} />;
}
